package io.github.guialmm.carteira.pix;

import static io.github.guialmm.carteira.pix.PixKeyException.Reason.EMAIL_NOT_YOURS;
import static io.github.guialmm.carteira.pix.PixKeyException.Reason.INVALID_KEY;
import static io.github.guialmm.carteira.pix.PixKeyException.Reason.KEY_LIMIT_REACHED;
import static io.github.guialmm.carteira.pix.PixKeyException.Reason.KEY_NOT_FOUND;
import static io.github.guialmm.carteira.pix.PixKeyException.Reason.KEY_TAKEN;

import io.github.guialmm.carteira.account.AccountRepository;
import io.github.guialmm.carteira.user.UserRepository;
import java.util.List;
import java.util.UUID;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

@Service
public class PixKeyService {

    /** Same limit the Central Bank sets for individuals. */
    public static final int MAX_KEYS_PER_ACCOUNT = 5;

    private final PixKeyRepository keys;
    private final AccountRepository accounts;
    private final UserRepository users;

    public PixKeyService(PixKeyRepository keys, AccountRepository accounts, UserRepository users) {
        this.keys = keys;
        this.accounts = accounts;
        this.users = users;
    }

    public record Owner(UUID accountId, String name) {
    }

    @Transactional
    public PixKey register(UUID accountId, PixKeyType type, String rawValue) {
        // Locking the account serializes key creation per account, so the limit cannot be raced.
        var account = accounts.findByIdForUpdate(accountId)
                .orElseThrow(() -> new PixKeyException(KEY_NOT_FOUND, "Account not found"));

        PixKeys.Parsed parsed;
        if (type == PixKeyType.RANDOM) {
            if (rawValue != null && !rawValue.isBlank()) {
                throw new PixKeyException(INVALID_KEY, "Random keys are generated by the server");
            }
            parsed = new PixKeys.Parsed(type, PixKeys.newRandomKey());
        } else {
            parsed = PixKeys.parse(type, rawValue);
        }

        // Without e-mail verification, only the e-mail you signed up with can become your key.
        if (type == PixKeyType.EMAIL) {
            String yours = users.findById(account.getOwnerId()).orElseThrow().getEmail();
            if (!yours.equals(parsed.value())) {
                throw new PixKeyException(EMAIL_NOT_YOURS, "Only your account e-mail can be an e-mail key");
            }
        }
        if (keys.countByAccountId(accountId) >= MAX_KEYS_PER_ACCOUNT) {
            throw new PixKeyException(KEY_LIMIT_REACHED, "An account can have at most %d keys".formatted(MAX_KEYS_PER_ACCOUNT));
        }
        if (keys.existsByTypeAndValue(parsed.type(), parsed.value())) {
            throw new PixKeyException(KEY_TAKEN, "This key is already registered");
        }
        try {
            return keys.saveAndFlush(new PixKey(accountId, parsed.type(), parsed.value()));
        } catch (DataIntegrityViolationException race) {
            throw new PixKeyException(KEY_TAKEN, "This key is already registered");
        }
    }

    @Transactional(readOnly = true)
    public List<PixKey> list(UUID accountId) {
        return keys.findByAccountIdOrderByCreatedAt(accountId);
    }

    @Transactional
    public void delete(UUID accountId, UUID keyId) {
        var key = keys.findById(keyId)
                .filter(k -> k.getAccountId().equals(accountId))
                .orElseThrow(() -> new PixKeyException(KEY_NOT_FOUND, "Key not found"));
        keys.delete(key);
    }

    /** Who receives a payment to this key. Accepts any format a person would type. */
    @Transactional(readOnly = true)
    public Owner resolve(String rawKey) {
        var parsed = PixKeys.detect(rawKey);
        var key = keys.findByTypeAndValue(parsed.type(), parsed.value())
                .orElseThrow(() -> new PixKeyException(KEY_NOT_FOUND, "No account has this key"));
        var account = accounts.findById(key.getAccountId()).orElseThrow();
        String name = users.findById(account.getOwnerId()).orElseThrow().getName();
        return new Owner(account.getId(), name);
    }
}
